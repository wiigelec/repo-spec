def render_structure(spec: dict) -> str:
    return (
        header("Repository Structure", "specs/repo/repository-structure.json")
        + "\n## Purpose\n\n"
        + f"{spec['normative_requirements'][0]['text']}\n\n"
        + "## Reference context\n\n"
        + "- `repo.manifest`\n"
        + "- `docs/plans/00-bootstrap-plan.md`\n"
    )


